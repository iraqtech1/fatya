import assert from 'node:assert/strict';
import {readPreviewOrders,savePreviewOrders,PREVIEW_ORDERS_KEY} from '../src/preview-orders.js';
import {matchesCustomer} from '../src/store.js';

const saved=new Map(),storage={getItem:key=>saved.get(key)??null,setItem:(key,value)=>saved.set(key,value)};
const alice={phone:'07712345678',email:''},bob={phone:'07812345678',email:''};
const first={id:'FATYA-A',name:'Zain',date:'2026-10-19',price:10000,value:10000,quantity:1,phone:alice.phone,status:'مكتمل',payment:'Qi'};
const second={...first,id:'FATYA-B',phone:bob.phone};
savePreviewOrders(storage,[first,second]);
const afterReload=readPreviewOrders(storage);
assert.deepEqual(afterReload,[first,second],'Purchase snapshots survive reload');
assert.deepEqual(afterReload.filter(o=>matchesCustomer(o,alice)),[first],'Each account sees only its own archived orders');
assert.deepEqual(afterReload.filter(o=>matchesCustomer(o,bob)),[second]);
const guest={previewId:'guest-a'},otherGuest={previewId:'guest-b'};
savePreviewOrders(storage,[{...first,phone:'',previewId:guest.previewId}]);
assert.equal(matchesCustomer(readPreviewOrders(storage)[0],guest),true);
assert.equal(matchesCustomer(readPreviewOrders(storage)[0],otherGuest),false);
saved.set(PREVIEW_ORDERS_KEY,'broken');assert.deepEqual(readPreviewOrders(storage),[]);
saved.set(PREVIEW_ORDERS_KEY,JSON.stringify([null,{},first,{...first,quantity:-1},{...first,phone:''}]));
assert.deepEqual(readPreviewOrders(storage),[first],'Malformed and unowned records are ignored');
assert.deepEqual(readPreviewOrders(),[]);
assert.throws(()=>savePreviewOrders({setItem(){throw Error('quota');}},[first]),/quota/,'Storage failures are reported to the purchase flow');
saved.clear();globalThis.localStorage=storage;
const purchase=await import('../src/store.js?archive-purchase');
const product=purchase.store.products[0];product.stock[0]=3;
const order=purchase.createOrder(product,0,2,alice,'ZainCash');
const reloaded=await import('../src/store.js?archive-reload');
assert.deepEqual(JSON.parse(JSON.stringify(reloaded.store.orders)),[order],'The real purchase flow persists its orders before reload');
assert.equal(reloaded.store.orders[0].unit,product.unit);
assert.equal(reloaded.store.orders[0].payment,'ZainCash');
storage.setItem=()=>{throw Error('quota');};
assert.throws(()=>purchase.createOrder(product,0,1,alice),/تعذّر حفظ الطلب/);
assert.equal(purchase.store.orders.length,1,'Failed persistence does not create a phantom purchase');
assert.equal(product.stock[0],1,'Failed persistence does not consume stock');
storage.setItem=(key,value)=>saved.set(key,value);
const anotherTab=await import('../src/store.js?archive-other-tab');
purchase.createOrder(product,0,1,alice);
anotherTab.createOrder(anotherTab.store.products[0],0,1,bob);
assert.equal(readPreviewOrders(storage).length,3,'Purchasing from a stale tab preserves purchases made in another tab');
console.log('Order archive persistence, account isolation and corrupt storage checks passed.');
