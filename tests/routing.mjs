import assert from 'node:assert/strict';
import {routePath,routeHref,inRoute,legacyDestination,navigateRoute} from '../src/routing.js';
assert.equal(routePath({pathname:'/admin/orders',hash:''},false),'/admin/orders');
assert.equal(routePath({pathname:'/fatya/',hash:'#/admin/orders'},true),'/admin/orders');
assert.equal(routeHref('/admin',false),'/admin');
assert.equal(routeHref('/admin',true),'#/admin');
assert.equal(inRoute('/admin/orders','/admin'),true);
assert.equal(inRoute('/administrator','/admin'),false);
assert.equal(legacyDestination({hash:'#/admin/orders',search:'?from=bookmark'}),'/admin/orders?from=bookmark');
assert.equal(legacyDestination({hash:'#/ar/business?type=host#contact',search:''}),'/ar/business?type=host#contact');
assert.equal(legacyDestination({hash:'#/',search:''}),'/');
assert.equal(legacyDestination({hash:'#/admin?from=bookmark',search:''}),'/admin?from=bookmark');
assert.equal(legacyDestination({hash:'#contact',search:''}),null);
assert.equal(legacyDestination({hash:'#//example.com',search:''}),null);
const events=[];
globalThis.history={state:null,pushState(state,_,path){this.state=state;globalThis.location.pathname=path}};
globalThis.location={pathname:'/admin'};
globalThis.PopStateEvent=class {constructor(type,options){this.type=type;this.state=options.state}};
globalThis.window={dispatchEvent(event){events.push(event.type)}};
navigateRoute('/admin/settings');
assert.equal(location.pathname,'/admin/settings');
assert.deepEqual(events,['popstate']);
console.log('Clean routes, preview URLs, legacy bookmarks and client navigation passed.');
